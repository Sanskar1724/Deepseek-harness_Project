"""Build a synthetic training dataset and write it to data/processed/.

Usage (from repo root, venv active, .env loaded):
    python -m ml.scripts.build_dataset
    python -m ml.scripts.build_dataset --n-points 2000 --seed 7
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Make `app` importable when running as a script from the repo root.
REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from ml.datasets.cards import write_card  # noqa: E402
from ml.datasets.synthetic import BuildConfig, build_synthetic_dataframe, write_synthetic_csv  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "data" / "processed"


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--n-points", type=int, default=600)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()

    df = build_synthetic_dataframe(BuildConfig(n_points=args.n_points, seed=args.seed))
    csv_path = write_synthetic_csv(df, args.out)
    write_card(
        csv_path,
        title="Synthetic NER landslide training frame",
        source=(
            "Generated by ml/datasets/synthetic.py. Features come from the "
            "registered providers (defaults: mock). Labels come from a noisy "
            "logistic function of those features."
        ),
        assumptions=[
            "The label `landslide_occurred` is NOT a real observation.",
            "It is the output of a synthetic data-generating process with "
            "deliberate noise so the resulting classifier is not trivially perfect.",
            "The bounding box is a rough NER rectangle; the real operating "
            "region should be replaced by district-level polygons.",
        ],
        production_replacement=(
            "Replace the synthetic_dataframe call with a real loader under "
"ml/datasets/loaders/ that reads from data/raw/ (GSI Bhukosh, NASA COOLR, "
"Bhuvan, etc.). The training script does not care where the dataframe comes "
"from as long as it has the columns listed in ml/datasets/synthetic.py::FEATURE_COLUMNS."
        ),
        df=df,
    )
    print(f"wrote {csv_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
